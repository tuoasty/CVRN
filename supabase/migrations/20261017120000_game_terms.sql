CREATE TABLE "public"."game_terms" (
    "kind"       text        NOT NULL,
    "tag"        text        NOT NULL,
    "category"   text        NOT NULL,
    "label"      text,
    "unit"       text,
    "template"   text,
    "grants"     text,
    "verified"   boolean     NOT NULL DEFAULT false,
    "updated_by" uuid,
    "updated_at" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT "game_terms_pkey" PRIMARY KEY ("kind", "tag"),
    CONSTRAINT "game_terms_kind_check" CHECK ("kind" IN ('effect', 'param')),
    CONSTRAINT "game_terms_effect_label" CHECK ("kind" <> 'effect' OR "label" IS NOT NULL),
    CONSTRAINT "game_terms_param_template" CHECK ("kind" <> 'param' OR "template" IS NOT NULL),
    CONSTRAINT "game_terms_updated_by_fkey" FOREIGN KEY ("updated_by") REFERENCES "auth"."users"("id") ON DELETE SET NULL
);

ALTER TABLE "public"."game_terms" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "anyone can read game_terms" ON "public"."game_terms"
    FOR SELECT TO "authenticated", "anon" USING (true);

CREATE POLICY "admins can insert game_terms" ON "public"."game_terms"
    FOR INSERT TO "authenticated"
    WITH CHECK ((EXISTS (SELECT 1 FROM "public"."user_roles"
        WHERE (("user_roles"."user_id" = (SELECT "auth"."uid"() AS "uid"))
            AND ("user_roles"."role" = ANY (ARRAY['admin'::"text", 'super_admin'::"text"]))))));

CREATE POLICY "admins can update game_terms" ON "public"."game_terms"
    FOR UPDATE TO "authenticated"
    USING ((EXISTS (SELECT 1 FROM "public"."user_roles"
        WHERE (("user_roles"."user_id" = (SELECT "auth"."uid"() AS "uid"))
            AND ("user_roles"."role" = ANY (ARRAY['admin'::"text", 'super_admin'::"text"]))))));

CREATE POLICY "admins can delete game_terms" ON "public"."game_terms"
    FOR DELETE TO "authenticated"
    USING ((EXISTS (SELECT 1 FROM "public"."user_roles"
        WHERE (("user_roles"."user_id" = (SELECT "auth"."uid"() AS "uid"))
            AND ("user_roles"."role" = ANY (ARRAY['admin'::"text", 'super_admin'::"text"]))))));

